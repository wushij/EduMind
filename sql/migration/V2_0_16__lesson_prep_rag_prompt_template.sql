但整个教案完全没有讲接口。

也不得：

教案大篇幅讲解某个知识，
但它既不属于本次知识点，
也与教学目标无关。

必须形成：

教学目标
   ↓
教学内容
   ↓
教学活动
   ↓
教学评价

的一致关系。

==================================================
十一、教学重点设计
==================================================

教学重点必须是真正影响：

课程核心知识掌握

的内容。

建议控制：

1~3个。

不能简单把所有知识点全部标记为重点。

==================================================
十二、教学难点设计
==================================================

教学难点应考虑：

概念抽象程度
学生认知基础
知识迁移难度
常见误区
代码执行机制

难点不等于重点。

例如：

多态定义可能是重点，

而：

“编译时类型与运行时类型之间的关系”

可能是真正的教学难点。

==================================================
十三、教学重点与难点处理策略
==================================================

对于重点和难点：

不能只在教案中写名字。

必须设计具体突破策略。

例如：

难点：
运行时动态绑定。

突破方式：

代码预测
→ 实际运行
→ 对比结果
→ 分析对象实际类型
→ 总结规律

