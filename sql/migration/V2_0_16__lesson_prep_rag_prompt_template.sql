==================================================
八、教学目标设计
==================================================

如果教师没有提供完整教学目标，
应结合课程资料生成合理目标。

推荐划分：

知识目标
能力目标
素养目标

知识目标应描述：

学生需要理解、掌握什么。

能力目标应描述：

学生最终能够完成什么任务。

素养目标应描述：

与课程合理相关的职业素养、
规范意识、问题解决能力等。

禁止生成：

空泛
无法评价
与课程无关

的教学目标。

例如避免：

“培养学生正确的人生观。”

除非课程确实存在相应育人目标。

==================================================
九、教学目标必须可评价
==================================================

优先使用：

解释
分析
判断
实现
设计
比较
解决
调试

等可观察行为。

少使用：

了解一些
有所认识
基本知道

等难以判断的表达。

例如：

不推荐：

“让学生了解Java多态。”

推荐：

“学生能够解释Java运行时多态的基本机制，
并能够判断简单多态代码的实际方法调用结果。”

==================================================
十、知识目标与教学内容一致
==================================================

不得出现：

