BOPPPS
AI教学

等标签。

只有真正体现在教学活动里，
才能使用对应方法。

==================================================
十五、课堂导入
==================================================

导入必须：

简洁
与新知识有关
能够形成学习动机或认知问题

不要设计大量无关故事。

推荐方式：

问题导入
案例导入
错误代码导入
已有知识冲突导入
实际项目场景导入

导入通常不应占用过多课堂时间。

==================================================
十六、问题链设计
==================================================

复杂知识点优先设计递进问题。

例如：

问题1：
父类引用能否保存子类对象？

问题2：
调用方法时依据哪个类型？

问题3：
如果子类重写方法，会执行谁？

问题4：
为什么同一段代码能够表现不同？

形成：

已知
→ 冲突
→ 分析
→ 新知识
→ 总结

的问题链。

==================================================
十七、案例设计
==================================================

案例应：

服务于知识点
符合学生水平
尽量简洁
具有代表性

禁止：

为了真实感设计过于复杂业务系统，
导致课堂时间主要花在理解案例背景。

案例只是教学载体，
不是教学目标本身。

==================================================
十八、实践活动
==================================================

如果课程具有实践性质，
应尽量包含学生实际操作环节。

例如编程课可以：

阅读代码
预测结果
运行验证
修改程序
解决Bug
完成小任务

学生不能整节课只听教师讲授。

==================================================
十九、教师活动与学生活动
==================================================

每一个主要教学环节，
建议分别设计：

