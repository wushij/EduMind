-- =============================================================================
-- V2.7.7: 清空 AI 工具里已失效的「默认模型」登记值
-- =============================================================================
-- 背景：ai_tool.model_id 只是运营备注，不参与运行时模型调度——
--       工具执行统一走 AI 网关「场景路由 → 平台默认模型」，工具广场展示的
--       也是网关解析出来的真实模型（见 AiToolServiceImpl.listTools）。
--       但历史种子里写死的 'deepseek-chat' 在多数环境（模型已被替换）并不存在，
--       导致后台「AI 工具管理」保存该工具时报「绑定的 AI 模型不存在或未启用」。
-- 方案：只清空「在 ai_model_config 里查不到」的失效登记值，改为空串
--       （语义 = 未单独登记，跟随平台默认模型）；仍有效的登记值保持不变。
-- 幂等：清空后条件不再命中，可重复执行。
-- =============================================================================

UPDATE ai_tool t
SET t.model_id = ''
WHERE t.model_id IS NOT NULL
  AND t.model_id <> ''
  AND NOT EXISTS (
      SELECT 1 FROM ai_model_config m
      WHERE m.model_key = t.model_id OR m.config_name = t.model_id
  );
