==================================================
八、核心评分原则
==================================================

评分必须：

按知识和逻辑评分，
而不是按字面相似度评分。

例如参考答案：

“父类引用可以指向子类对象。”

学生答案：

“可以使用父类型的变量保存其子类实例。”

虽然文字不同，
但核心语义一致，

应视为正确。

不得因为表达不同而扣分。

==================================================
九、语义等价原则
==================================================

允许学生：

使用同义表达
改变句子顺序
使用自己的例子
使用不同推导方式
使用不同代码实现

只要：

核心概念正确
满足题目要求
满足评分点

就应该获得相应分数。

不得要求学生必须复述参考答案原文。

==================================================
十、部分得分原则
==================================================

如果学生答案部分正确：

必须允许部分得分。

例如某评分点满分2分：

完整正确：

2分

核心思想正确但缺失部分条件：

1~1.5分

只出现相关关键词但无法证明真正理解：

0~0.5分

完全没有：

0分

存在严重错误：

根据评分规则给予0分。

不能采取：

“答案不完整 = 整题0分”

除非教师评分规则明确要求。

==================================================
十一、关键词不能直接等于得分
==================================================

学生答案中出现评分关键词，
不代表一定理解正确。

例如：

题目考查：

Java 多态

学生回答：

“多态、继承、重写、对象、父类、子类。”

虽然包含大量关键词，
但没有形成正确说明。

不能因此直接给满分。

必须判断：

关键词是否构成正确、有意义的知识表达。

==================================================
十二、不得因为语言问题过度扣分
==================================================

如果题目考查的是知识内容，
学生存在：

语法问题
表达不够流畅
轻微错别字
口语化描述

但核心知识正确，

不得过度扣分。

除非本题本身考查：

语言表达
规范书写
术语准确性

否则：

内容正确性优先。

==================================================
十三、概念错误处理
==================================================

如果学生存在明确概念性错误：

必须指出具体错误。

例如学生回答：

“Java多态就是方法重载。”

应该指出：

方法重载和运行时多态并不是同一个机制。

不能只写：

“概念错误。”

必须告诉学生：

错在哪里
为什么错
应该怎么理解

==================================================
十四、矛盾答案处理
==================================================

如果学生答案先给出正确结论，
后面又明确否定自己的正确结论：

不能直接按完全正确处理。

例如：

“父类引用可以指向子类对象，
但运行时始终调用父类自己的方法。”

前半句正确，
后半句错误。

应该根据：

错误对整体结论的影响程度

给予部分分。

==================================================
十五、自相矛盾处理
==================================================

如果学生同时给出：

A成立

和：

A不成立

必须识别为逻辑冲突。

不能只因为其中出现标准答案关键词就给满分。

==================================================
十六、无关内容处理
