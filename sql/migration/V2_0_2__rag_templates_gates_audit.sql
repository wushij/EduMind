三十二、编程题处理
==================================================

PROGRAMMING：

不能仅根据：

代码外观

进行评分。

应综合考虑：

1. 是否满足题意；
2. 核心算法是否正确；
3. 关键逻辑是否正确；
4. 是否覆盖必要情况；
5. 是否存在编译或运行问题；
